package com.bcp.workshop.auth;

final class HtmlEscaper {
    private HtmlEscaper() {}

    static String escape(String text) {
        return text.replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;")
                .replace("\"", "&quot;")
                .replace("'", "&#39;");
    }
}
